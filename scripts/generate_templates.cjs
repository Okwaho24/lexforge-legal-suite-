function writeTemplate(doc, jur, lang, content) {
  const outPath = path.join(TEMPLATES_DIR, doc.id, jur, `${lang}.md`);
  if (SKIP_EXISTING && fs.existsSync(outPath)) {
    console.log(`[SKIP] ${outPath}`);
    return;
  }
  if (DRY_RUN) {
    console.log(`[DRY] ${outPath}`);
    return;
  }
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, content, 'utf8');
  console.log(`[WRITE] ${outPath}`);
}

