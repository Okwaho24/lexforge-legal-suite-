let errors = 0;

for (const jur of jurisdictionsToRun) {
  const rules = JURISDICTION_RULES[jur];
  if (!rules) { console.error(`[ERROR] Unknown jurisdiction: ${jur}`); errors++; continue; }
  const languages = JURISDICTION_LANGUAGES[jur];
  const acerbe = getAcerbeClause(jur);

  for (const doc of DOCS) {
    for (const lang of languages) {
      try {
        const bodyFn = BODY_BUILDERS[doc.id];
        const body = bodyFn(jur, lang, rules, acerbe);
        const content = [
          buildFrontmatter(doc, jur, lang, rules),
          buildHeader(doc, jur, lang, rules),
          body,
          buildFooter(doc, jur, rules, acerbe),
        ].join('\n\n');
        writeTemplate(doc, jur, lang, content);
      } catch (e) {
        console.error(`[ERROR] ${doc.id}/${jur}/${lang}: ${e.message}`);
        errors++;
      }
    }
  }
}

if (errors > 0) {
  console.error(`\n[FAILED] ${errors} error(s) encountered.`);
  process.exit(1);
} else {
  console.log('\n[DONE] All templates generated successfully.');
}
